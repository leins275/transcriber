#!/usr/bin/env python3
# /// script
# requires-python = ">=3.12"
# dependencies = ["packaging>=24"]
# ///
"""Generate the pinned wheel manifest for the first-run OpenVINO whisper runtime.

The installer never bakes the `whisper-openvino` extra (OpenVINO GenAI and
the OpenVINO runtime, ~50 MB that only an Intel NPU/GPU machine without an
NVIDIA GPU would use); the service fetches it at first run into
`<app_dir>/runtime/whisper-openvino/` instead, exactly like the speaker
runtime. This script derives the wheel list from
`services/transcription/uv.lock` -- every package the extra adds on top of
what the installer bakes (`build_pyenv.BASE_EXTRAS`), for CPython 3.12 on
`win_amd64` -- reusing `gen_diarization_runtime.py`'s lock walker.

Output: `services/transcription/src/transcription/openvino_runtime_packages.py`
(committed; `--check` verifies it is up to date, which `make lint` runs).

Usage:
    uv run scripts/gen_openvino_runtime.py           # rewrite the module
    uv run scripts/gen_openvino_runtime.py --check   # verify, exit 1 on drift
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from gen_diarization_runtime import (  # noqa: E402 - sibling script, path set above
    BASE_EXTRAS,
    LOCK_FILE,
    PLATFORM,
    PYTHON_VERSION,
    REPO_ROOT,
    Lock,
    Wheel,
    _closure,
    _pick_wheel,
    _quoted,
    _render_wheel,
    _supported_tags,
)

OUTPUT_FILE = (
    REPO_ROOT
    / "services"
    / "transcription"
    / "src"
    / "transcription"
    / "openvino_runtime_packages.py"
)
RUNTIME_EXTRA = "whisper-openvino"


def compute_wheels(lock_path: Path = LOCK_FILE) -> list[Wheel]:
    lock = Lock(lock_path)
    base = _closure(lock, frozenset(BASE_EXTRAS))
    full = _closure(lock, frozenset(BASE_EXTRAS) | {RUNTIME_EXTRA})
    added = {name: package for name, package in full.items() if name not in base}
    for required in ("openvino-genai", "openvino", "openvino-tokenizers"):
        if required not in added:
            raise SystemExit(f"expected {required!r} in the openvino closure; got none")
    supported = _supported_tags()
    return [_pick_wheel(added[name], supported) for name in sorted(added)]


def render(wheels: list[Wheel]) -> str:
    lines = [
        '"""The pinned wheels of the first-run OpenVINO whisper runtime.',
        "",
        "GENERATED by `scripts/gen_openvino_runtime.py` from",
        "`services/transcription/uv.lock` -- do not edit by hand; `make lint`",
        "fails when this file drifts from the lock. Every package the",
        f"`{RUNTIME_EXTRA}` extra adds on top of the baked environment, for",
        f"CPython {PYTHON_VERSION[0]}.{PYTHON_VERSION[1]} on {PLATFORM}. Consumed by",
        "`transcription.openvino_runtime`.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import NamedTuple",
        "",
        "",
        "class Wheel(NamedTuple):",
        "    name: str",
        "    version: str",
        "    filename: str",
        "    url: str",
        "    size: int",
        "    sha256: str",
        '    archive_root: str = ""',
        '    extract_prefix: str = ""',
        "",
        "",
        "OPENVINO_WHEELS: tuple[Wheel, ...] = (",
    ]
    for wheel in wheels:
        _render_wheel(lines, wheel, "    ")
    lines.append(")")
    lines.append(f"TOTAL_BYTES: int = {sum(w.size for w in wheels)}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="Verify; exit 1 on drift.")
    parser.add_argument("--lock", type=Path, default=LOCK_FILE, help=argparse.SUPPRESS)
    parser.add_argument("--output", type=Path, default=OUTPUT_FILE, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    rendered = render(compute_wheels(args.lock))
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.is_file() else ""
        if current != rendered:
            print(
                f"{args.output} is out of date; run: uv run scripts/gen_openvino_runtime.py",
                file=sys.stderr,
            )
            return 1
        print("openvino runtime manifest matches uv.lock")
        return 0
    args.output.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

# `_quoted` is re-exported for the test suite's convenience.
__all__ = ["compute_wheels", "render", "main", "_quoted"]
